import { writeFile } from 'node:fs/promises'
import { artists, albums, tracks } from './catalog.mjs'

function sql(value) {
  if (value === null) return 'null'
  if (Array.isArray(value)) return 'array[' + value.map(sql).join(', ') + ']::text[]'
  if (typeof value === 'number') return String(value)
  return "'" + value.replaceAll("'", "''") + "'"
}

const statements = Object.entries({ artists, albums, tracks }).map(([table, rows]) => {
  const primaryKey = table === 'tracks' ? 'id' : 'slug'
  const columns = Object.keys(rows[0])
  const updates = columns.filter(column => column !== primaryKey).map(column => column + ' = excluded.' + column)
  const values = rows.map(row => '  (' + columns.map(column => sql(row[column])).join(', ') + ')')
  return 'insert into public.' + table + ' (' + columns.join(', ') + ') values\n'
    + values.join(',\n') + '\non conflict (' + primaryKey + ') do update set\n  ' + updates.join(',\n  ') + ';'
})

await writeFile(new URL('./supabase/seed.sql', import.meta.url),
  '-- Generated by npm run seed:generate -w api from api/catalog.mjs.\n\nbegin;\n\n'
  + statements.join('\n\n') + '\n\ncommit;\n')
